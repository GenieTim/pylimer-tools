#!/usr/bin/env python
"""
Analyse Networks
================

This script provides a command-line interface (CLI) to analyze polymer networks
generated by LAMMPS simulations. It reads structure files, computes various
properties of the networks, and outputs statistics such as bond lengths,
end-to-end distances, and stoichiometric imbalances.
"""

import statistics
from typing import Tuple

import click

from pylimer_tools.calc.structure_analysis import (
    compute_crosslinker_conversion,
    compute_extent_of_reaction,
    compute_stoichiometric_imbalance,
)
from pylimer_tools.io.bead_spring_parameter_provider import (
    ParameterType,
    get_parameters_for_polymer,
    get_supported_polymer_names,
)
from pylimer_tools.io.read_lammps_output_file import read_data_file
from pylimer_tools_cpp import (
    EntanglementMode,
    HookeanForceEvaluator,
    MEHPLinearSolverConfig,
    MEHPSimulator,
    SLESolver,
    SlipMode,
    StructureSimplificationMode,
)


@click.command()
@click.argument("files", nargs=-1, type=click.Path(exists=True))
@click.option("--crosslinker-type", type=int, default=2)
@click.option(
    "--polymer-name",
    type=click.Choice(get_supported_polymer_names(), case_sensitive=False),
    default="PDMS",
    help="Name of the polymer to use for parameter retrieval.",
)
@click.option(
    "--parameter-type",
    type=click.Choice(["GAUSSIAN", "KG_LJ", "KUHN"], case_sensitive=False),
    default="GAUSSIAN",
    help="Type of parameters to use for the polymer model.",
)
def cli(
    files: Tuple[str, ...],
    crosslinker_type: int,
    polymer_name: str,
    parameter_type: str,
) -> None:
    """
    Basic CLI application reading all passed files, outputting some stats on the structures therein

    Arguments:
      - files: list of files to read
    """
    click.echo("Processing {} files".format(len(files)))
    params = get_parameters_for_polymer(
        polymer_name=polymer_name,
        parameter_type=ParameterType[parameter_type.upper()],
    )
    base_distance_quantity = params.get_base_distance_units()
    base_distance_unit = base_distance_quantity.units
    sim_length_unit = (
        str(base_distance_unit)
        if (
            not base_distance_quantity.dimensionless
            and base_distance_quantity.magnitude == 1
        )
        else "u"
    )

    for file_path in files:
        click.echo(
            "\nAnalysing File with {} units ".format(params.get_name()) + file_path
        )

        universe = read_data_file(file_path)

        click.echo(
            "Size: {}. Volume: {} {}^3 (ρ = {} atoms/{}^3)".format(
                universe.get_nr_of_atoms(),
                universe.get_volume(),
                sim_length_unit,
                universe.get_nr_of_atoms() / universe.get_volume(),
                sim_length_unit,
            )
        )
        click.echo(
            "{} atoms and {} bonds, {} angles, {} dihedrals".format(
                universe.get_nr_of_atoms(),
                universe.get_nr_of_bonds(),
                universe.get_nr_of_angles(),
                universe.get_nr_of_dihedral_angles(),
            )
        )
        molecules = universe.get_molecules(crosslinker_type)
        bond_lengths = universe.compute_bond_lengths()
        non_none_bond_lengths = [bl for bl in bond_lengths if bl is not None and bl > 0]
        if non_none_bond_lengths:
            click.echo(
                "Bond length b: <b> = {} {}, (min: {}, max: {}, median: {}) {}, <b^2> = {} {}^2".format(
                    statistics.mean(non_none_bond_lengths),
                    sim_length_unit,
                    min(non_none_bond_lengths),
                    max(non_none_bond_lengths),
                    statistics.median(non_none_bond_lengths),
                    sim_length_unit,
                    statistics.mean(bl**2 for bl in non_none_bond_lengths),
                    sim_length_unit,
                )
            )
        else:
            click.echo("Bond length b: n/a (no positive bond lengths)")

        end_to_end_distances = universe.compute_end_to_end_distances(
            crosslinker_type=crosslinker_type, derive_image_flags=True
        )
        non_none_end_to_end_distances = [
            e for e in end_to_end_distances if e is not None and e > 0
        ]
        if non_none_end_to_end_distances:
            click.echo(
                "End to end distance R_ee: <R_ee> = {} {}, <R_ee^2> = {} {}^2".format(
                    statistics.mean(non_none_end_to_end_distances),
                    sim_length_unit,
                    statistics.mean(e**2 for e in non_none_end_to_end_distances),
                    sim_length_unit,
                )
            )
        else:
            click.echo("End to end distance R_ee: n/a")

        mean_mol_len = (
            statistics.mean([m.get_nr_of_atoms() for m in molecules])
            if molecules
            else 0.0
        )
        click.echo(
            "For {} molecules of mean length of {} atoms".format(
                len(molecules),
                mean_mol_len,
            )
        )
        click.echo(
            "f = {}, r = {}, p = {} ({}), D = {}".format(
                universe.determine_functionality_per_type().get(crosslinker_type, 0),
                compute_stoichiometric_imbalance(universe, crosslinker_type),
                compute_extent_of_reaction(universe, crosslinker_type),
                compute_crosslinker_conversion(universe, crosslinker_type),
                universe.compute_polydispersity_index(crosslinker_type),
            )
        )

        # Conduct force balance analysis
        mehp: MEHPSimulator = MEHPSimulator.construct_with_random_entanglements(
            universe,
            int(params.get_entanglement_density() * universe.get_volume()),
            params.get_sampling_cutoff(),
            crosslinker_type=crosslinker_type,
            entanglement_mode=EntanglementMode.MERGED_LINKS,
        )
        mehp.set_force_evaluator(HookeanForceEvaluator(1.0))

        solver_config: MEHPLinearSolverConfig = MEHPLinearSolverConfig()
        solver_config.solver = SLESolver.DEFAULT
        solver_config.slip_mode = SlipMode.FIXED
        solver_config.simplification_mode = (
            StructureSimplificationMode.NO_SIMPLIFICATION
        )
        mehp.run(solver_config)

        click.echo(
            "Shear Modulus [MPa]: {:.2f}".format(
                params.get_gamma_conversion_factor().to("MPa").magnitude
                * sum(
                    mehp.get_gamma_factors(
                        params.get("R02")
                        .to(params.get("distance_units") ** 2)
                        .magnitude
                    )
                )
                / universe.get_volume()
            )
        )
        click.echo(
            "w_sol = {:.3f}, w_dang = {:.3f}, w_active = {:.3f}".format(
                mehp.get_soluble_weight_fraction(),
                mehp.get_dangling_weight_fraction(),
                mehp.get_active_weight_fraction(),
            )
        )

        click.echo("")
    if base_distance_quantity.dimensionless:
        click.echo(
            "Reduced/arbitrary length units used ({}), Shear Modulus: MPa".format(
                params.get_name()
            )
        )
    elif base_distance_quantity.magnitude == 1:
        click.echo(
            "Units used ({}): Length: {}, Shear Modulus: MPa".format(
                params.get_name(), base_distance_unit
            )
        )
    else:
        click.echo(
            "Units used ({}): 1 simulation length unit = {:.4g} {}, Shear Modulus: MPa".format(
                params.get_name(),
                base_distance_quantity.magnitude,
                base_distance_unit,
            )
        )


if __name__ == "__main__":
    cli()
